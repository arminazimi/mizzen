// Measures incremental builds on a generated site: the cold build, a no-op build, one focused body edit, and the same
// edit built from scratch. It prints wall time and the pages actually rendered, then compares the incremental output
// with the clean one byte for byte. Nothing is committed and no target is asserted: docs/performance.md records the
// numbers from one machine and node, so a later change can be compared on the same machine.
//
// Usage: node scripts/bench-incremental.ts [--pages 400] [--theme ../lateen]
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build, type BuildResult } from "../src/pipeline/build.ts";

const args = process.argv.slice(2);
const valueOf = (flag: string, fallback: string): string => {
  const index = args.indexOf(flag);
  return index === -1 ? fallback : (args[index + 1] ?? fallback);
};
const PAGES = Number(valueOf("--pages", "400"));
const THEME = fileURLToPath(new URL(valueOf("--theme", "../../lateen"), import.meta.url));

function generate(root: string): void {
  mkdirSync(join(root, "_data"), { recursive: true });
  mkdirSync(join(root, "_snippets"), { recursive: true });
  writeFileSync(join(root, "mizzen.yml"), "title: Scale fixture\ndescription: Generated by scripts/bench-incremental.ts.\nlang: en\n");
  writeFileSync(join(root, "_snippets", "note.md"), "Shared note.\n");
  const nav = ["main:"];
  nav.push("  - title: Home\n    url: /");
  for (let i = 1; i <= PAGES; i++) {
    const name = `page-${String(i).padStart(4, "0")}`;
    const body = [`# ${name}`, "", "A paragraph of ordinary documentation prose.", ""];
    if (i % 10 === 0) body.push("::include[_snippets/note.md]");
    writeFileSync(join(root, `${name}.md`), `---\ntitle: ${name}\n---\n${body.join("\n")}\n`);
    nav.push(`  - title: ${name}\n    url: /${name}/`);
  }
  writeFileSync(join(root, "_data", "navigation.yml"), `${nav.join("\n")}\n`);
}

function snapshot(dir: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const rel of readdirSync(dir, { recursive: true }) as string[]) {
    const abs = join(dir, rel);
    if (statSync(abs).isFile()) map.set(rel.split("\\").join("/"), readFileSync(abs).toString("latin1"));
  }
  return map;
}

function same(a: Map<string, string>, b: Map<string, string>): boolean {
  if (a.size !== b.size) return false;
  for (const [path, bytes] of a) if (b.get(path) !== bytes) return false;
  return true;
}

async function timed(run: () => Promise<BuildResult>): Promise<{ result: BuildResult; ms: number }> {
  const start = performance.now();
  const result = await run();
  return { result, ms: performance.now() - start };
}

const parent = mkdtempSync(join(tmpdir(), "mizzen-bench-"));
try {
  const root = join(parent, "site");
  mkdirSync(root, { recursive: true });
  generate(root);
  const out = join(parent, "out");
  const clean = join(parent, "clean");
  const cacheDir = join(parent, "cache");
  const base = { root, themeRoot: THEME, defaultLayout: "doc" };

  const cold = await timed(() => build({ ...base, out, cache: false }));
  const populate = await timed(() => build({ ...base, out, cache: true, cacheDir }));
  const noop = await timed(() => build({ ...base, out, cache: true, cacheDir }));
  writeFileSync(join(root, "page-0100.md"), `---\ntitle: page-0100\n---\n# page-0100\n\nA paragraph, edited.\n`);
  const incremental = await timed(() => build({ ...base, out, cache: true, cacheDir }));
  const reference = await timed(() => build({ ...base, out: clean, cache: false }));
  const identical = same(snapshot(out), snapshot(clean));

  const rows = [
    ["cold build", cold],
    ["first cached build", populate],
    ["no-op build", noop],
    ["one body edit (incremental)", incremental],
    ["same edit from scratch", reference],
  ] as const;
  console.log(`pages=${PAGES} theme=${THEME} node=${process.version} ${process.platform}/${process.arch}`);
  console.log("phase                          ms   rendered  cached");
  for (const [name, { result, ms }] of rows) {
    console.log(`${name.padEnd(30)} ${Math.round(ms).toString().padStart(5)}  ${String(result.renderedPages).padStart(8)}  ${String(result.cachedPages).padStart(6)}`);
  }
  console.log(`incremental output equals clean build: ${identical ? "yes" : "NO"}`);
  if (!identical) process.exitCode = 1;
} finally {
  rmSync(parent, { recursive: true, force: true });
}
